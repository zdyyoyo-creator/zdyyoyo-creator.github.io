/* ==========================================================================
   ★ 这是给你留的「文件接口」★
   --------------------------------------------------------------------------
   想往网站上放自己的东西（简历 PDF、照片、证书、压缩包……），只要三步：

   1. 把文件复制到本页面所在的 files/ 文件夹里
      （文件名建议用英文或数字，比如 resume.pdf、photo-1.jpg，中文名也能用）

   2. 在下面的 [ ] 里照抄一段，改掉这四个值：
        name → 显示在网页上的标题
        file → 从网站根目录开始的路径，一定是 "files/你的文件名"
        desc → 一句话说明（会显示在标题下面）
        tag  → 左上角徽章，写 PDF / DOC / IMG / ZIP 都行，不填就是文件后缀

   3. 保存文件 → 刷新网页（上传到 GitHub 后就是 git push），
      「我的文件」区块里马上多一张下载卡片。

   多条记录之间用英文逗号隔开，最后一条不要加逗号。
   ========================================================================== */

